# (a) Criar e inicializar o vetor A com 6 inteiros
A = [1, 0, 5, -2, -5, 7]

# (b) Somar os valores das posições A[0], A[1] e A[5]
soma = A[0] + A[1] + A[5]
print(f"Soma dos elementos nas posições 0, 1 e 5: {soma}")

# (c) Modificar o valor da posição 4 para 100
A[4] = 100

# (d) Imprimir cada valor do vetor A, um por linha
print("\nElementos do vetor A:")
for valor in A:
    print(valor)